import { inject } from '@angular/core';
import { CanActivateFn, Router } from '@angular/router';
import { AuthService } from '../services/auth.service';

/**
 * Blocks navigation to any route it's attached to unless `AuthService`
 * reports an authenticated session, redirecting to `/login` with the
 * originally-requested URL preserved as `returnUrl` so a successful login
 * can send the user back where they meant to go.
 */
export const authGuard: CanActivateFn = (_route, state) => {
  const authService = inject(AuthService);
  const router = inject(Router);

  if (authService.isAuthenticated()) {
    return true;
  }

  router.navigate(['/login'], { queryParams: { returnUrl: state.url } });
  return false;
};
